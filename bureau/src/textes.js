// Les textes du guide et de l'installation vivent à part (taille des fichiers).
const GUIDE = require('./textes-guide');
for (const l of Object.keys(TEXTES)) Object.assign(TEXTES[l], GUIDE[l]);

let langue = 'en';

function choisirLangue(locale) {
  langue = String(locale || '').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

function t(cle, valeurs = {}) {
  const brut = TEXTES[langue][cle] ?? TEXTES.en[cle] ?? cle;
  return brut.replace(/\{(\w+)\}/g, (_, k) => valeurs[k] ?? '');
}

const tous = () => ({ langue, textes: TEXTES[langue] });

module.exports = { choisirLangue, t, tous };
